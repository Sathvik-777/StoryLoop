
from pathlib import Path

from youtube_publisher import YouTubePublisher
from api_cost_tracker import get_cost_tracker


PROJECT_ROOT = Path(__file__).resolve().parent.parent

# Replace this with the path to an existing rendered StoryLoop MP4.
VIDEO_PATH = PROJECT_ROOT / "output" / "current_run" / "rendered" / "story_video.mp4"

publisher = YouTubePublisher()

result = publisher.upload_video(
    video_path=VIDEO_PATH,
    title="StoryLoop - First Test Upload",
    description="A test upload generated by StoryLoop.",
    tags=["StoryLoop", "short story", "storytelling"],
    privacy_status="private",
)

print("\nUpload successful!")
print(f"Title: {result['title']}")
print(f"Video ID: {result['video_id']}")
print(f"URL: {result['url']}")
print(f"Privacy: {result['privacy_status']}")
print(f"API cost report: {get_cost_tracker().write_report()}")
